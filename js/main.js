async function submitForm(
    form,
    endpoint,
    statusEl,
    successText
) {
    if (!endpoint) {
        statusEl.textContent =
            'The form is live on the website. Add your Formspree endpoint '
            + 'in FORM_ENDPOINTS at the top of the script to receive submissions.';
        return;
    }

    const button = form.querySelector('button[type=submit]');
    button.disabled = true;
    button.textContent = 'Sending…';

    try {
        const response = await fetch(endpoint, {
            method: 'POST',
            body: new FormData(form),
            headers: {
                'Accept': 'application/json'
            }
        });

        if (!response.ok) {
            throw new Error('Request failed');
        }

        form.reset();
        statusEl.textContent = successText;
    } catch (error) {
        statusEl.textContent =
            'Something went wrong. Please try again or use the social links below.';
    } finally {
        button.disabled = false;
        button.textContent = successText.includes('mentoring')
            ? 'Request a mentoring conversation ↗'
            : 'Send message ↗';
    }
}
